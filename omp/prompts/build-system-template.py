#!/usr/bin/env python3
"""Build ~/.omp/agent/SYSTEM_TEMPLATE.md: DeepSeek block 0 for DeepSeek models, OMP's bundled block 0 otherwise.

OMP renders SYSTEM_TEMPLATE.md in place of its bundled system-prompt.md and re-renders it when the
session model changes (including the task prewalk handoff). The template engine has no inline
partials and `when` compares exactly, so the DeepSeek block is emitted once per matched `model` value.

The bundled branch must match the installed OMP release. The script fetches system-prompt.md for the
installed version and refuses to build when it differs from the vendored copy; review the upstream
diff, update deepseek-block0.hbs if needed, then rerun with --accept-upstream.
"""

import argparse
import difflib
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEEPSEEK_BLOCK = HERE / "deepseek-block0.hbs"
VENDORED = HERE / "upstream-system-prompt.md"
TARGET = HERE.parent / "SYSTEM_TEMPLATE.md"
UPSTREAM_URL = "https://raw.githubusercontent.com/can1357/oh-my-pi/v{version}/packages/coding-agent/src/prompts/system/system-prompt.md"
# Exact `model` values OMP renders are "provider/id" plus ":<effort>" since omp 18.5.0
# (`formatModelSelectorValue`; bare when the level is unset). includeModelInPrompt must stay true.
DEEPSEEK_MODELS = ("omni/opencode-go/deepseek-v4.1-flash", "deepseek/deepseek-flash")
# pi-agent `ThinkingLevel` minus `inherit`, which formatModelSelectorValue never appends.
EFFORT_SUFFIXES = ("", ":off", ":minimal", ":low", ":medium", ":high", ":xhigh", ":max")
MODEL_VALUES = tuple(model + suffix for model in DEEPSEEK_MODELS for suffix in EFFORT_SUFFIXES)


def installed_version() -> str:
    out = subprocess.run(["omp", "--version"], capture_output=True, text=True, check=True).stdout
    match = re.search(r"(\d+\.\d+\.\d+)", out)
    if not match:
        sys.exit(f"cannot parse omp version from {out!r}")
    return match.group(1)


def fetch_upstream(version: str) -> str:
    with urllib.request.urlopen(UPSTREAM_URL.format(version=version), timeout=30) as response:
        return response.read().decode()


def assemble(version: str, deepseek: str, bundled: str) -> str:
    deepseek = deepseek.rstrip("\n") + "\n"
    bundled = bundled.rstrip("\n") + "\n"
    header = (
        f"{{{{!-- Generated by dotfiles omp/prompts/build-system-template.py for omp {version}. "
        "Edit deepseek-block0.hbs and rebuild; do not edit this file. --}}\n"
    )
    out = header
    for model in MODEL_VALUES:
        out += f'{{{{#when model "==" "{model}"}}}}\n{deepseek}{{{{else}}}}\n'
    out += bundled
    out += "{{/when}}\n" * len(MODEL_VALUES)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--accept-upstream", action="store_true", help="replace the vendored bundled template")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the target")
    args = parser.parse_args()

    version = installed_version()
    upstream = fetch_upstream(version)
    vendored = VENDORED.read_text() if VENDORED.exists() else ""
    if upstream != vendored:
        if not args.accept_upstream:
            diff = difflib.unified_diff(vendored.splitlines(), upstream.splitlines(), "vendored", f"omp {version}", lineterm="")
            print("\n".join(diff))
            sys.exit(f"bundled system-prompt.md changed in omp {version}; review, then rerun with --accept-upstream")
        VENDORED.write_text(upstream)

    template = assemble(version, DEEPSEEK_BLOCK.read_text(), upstream)
    if args.stdout:
        sys.stdout.write(template)
        return
    TARGET.write_text(template)
    print(f"wrote {TARGET} ({len(template)} bytes) for omp {version}")


if __name__ == "__main__":
    main()
